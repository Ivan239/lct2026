"""Три варианта вёрстки одной колоды (требование ТЗ, п. 3.6).

Ось различий выбрана так, чтобы варианты были видны глазом и при этом одинаково
подчинялись правилам шаблона: меняется ПЛАН колоды, а не вёрстка. Вёрстка у всех
трёх одна и та же — те же слоты, те же кегли, те же проверки, поэтому ни один
вариант не может нарушить шаблон сильнее другого.

Что различается:

- «компактный» — короткая колода, вывод в начале, до трёх пунктов на слайде;
- «подробный» — длинная колода, классический порядок, дробление слайдов;
- «визуальный» — приоритет визуальных ролей (показатели, сравнение, иллюстрация)
  над текстовыми списками.

Плотность задаётся числом слайдов (код: позиция в диапазоне 10–15), остальное — короткой добавкой к промпту
плана, отдельным файлом на вариант (`prompts/variant_*.v1.txt`).
"""

from common.prompt_files import load_prompt

VARIANTS = {
    "compact": {
        "title": "Компактный",
        "prompt": "variant_compact.v1.txt",
        "position": 0.0,       # место в диапазоне ТЗ: нижняя граница
        "description": "вывод в начале, до трёх пунктов на слайде, минимум разделителей",
    },
    "detailed": {
        "title": "Подробный",
        "prompt": "variant_detailed.v1.txt",
        "position": 1.0,       # верхняя граница
        "description": "шаг за шагом, разделители между частями, 4–5 пунктов на слайде",
    },
    "visual": {
        "title": "Визуальный",
        "prompt": "variant_visual.v1.txt",
        "position": 0.5,       # середина
        "description": "показатели, сравнения и иллюстрации вместо текстовых списков",
    },
}

DEFAULT_VARIANT = "detailed"


def variant_names():
    return list(VARIANTS)


def variant_preamble(variant):
    """Добавка к промпту плана для этого варианта («» — для варианта по умолчанию)."""
    spec = VARIANTS.get(variant)
    if not spec or variant == DEFAULT_VARIANT:
        return ""
    return load_prompt(spec["prompt"])


def variant_slides(variant, slides, low=10, high=15):
    """Сколько слайдов просить у плана для этого варианта.

    `slides` — то, что заказал пользователь; None — диапазон брифа 10–15.

    Ось задаётся ПОЗИЦИЕЙ в диапазоне, а не множителем от заказа: множитель
    упирается в нижнюю границу и схлопывает варианты в один. При заказе 10
    (ровно нижняя граница ТЗ) `0.7 × 10 = 7` обрезалось до 10 — и «компактный»
    выходил той же длины, что «визуальный»; девять сданных колод отличались
    только перестановкой слайдов. Без заказа варианты раскладываются по всему
    диапазону (10/13/15), с заказом — расходятся вокруг него и обрезаются
    границами ТЗ."""
    spec = VARIANTS.get(variant)
    if not spec:
        return slides
    position = spec["position"]
    if slides:
        span = max(1, round((high - low) / 2))
        target = slides + round((position - 0.5) * 2 * span)
    else:
        target = round(low + position * (high - low))
    return max(low, min(high, target))
